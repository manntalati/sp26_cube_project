import threading
import time
from dataclasses import dataclass, field
from queue import Queue, Empty
from typing import Any, Dict, List, Optional, Tuple, Union

from services.fireflies_service import get_transcript_full
from services.gemini_service import analyze_action_items


@dataclass(frozen=True)
class AnalysisJob:
    """Analysis job that fetches transcript from Fireflies before Gemini."""
    transcript_id: str
    fireflies_api_key: str
    gemini_api_key: str


@dataclass(frozen=True)
class InPersonJob:
    """
    Analysis job for in-person sessions.

    The transcript_text is already built (Deepgram → adapter layer);
    no Fireflies call is needed.  The transcript_id is the session_id
    generated by the renderer so it works as a key in ANALYSIS_STORE.

    participants is a list of {speaker_id, name, email} dicts used to give
    Gemini a deterministic participant roster (replaces fuzzy alias matching).
    """
    transcript_id: str
    transcript_text: str
    gemini_api_key: str
    action_items: List[str] = field(default_factory=list)
    participants: List[Dict] = field(default_factory=list)
    # Not used but kept for structural parity with AnalysisJob
    fireflies_api_key: str = ""


# transcript_id -> record
ANALYSIS_STORE: Dict[str, Dict[str, Any]] = {}

_queue: "Queue[Union[AnalysisJob, InPersonJob]]" = Queue()
_worker_started = False
_lock = threading.Lock()


def _now_ms() -> int:
    return int(time.time() * 1000)


def get_analysis_record(transcript_id: str) -> Dict[str, Any]:
    """
    Returns the current analysis record (creates a default one if missing).
    """
    with _lock:
        rec = ANALYSIS_STORE.get(transcript_id)
        if not rec:
            rec = {
                "transcript_id": transcript_id,
                "status": "not_queued",  # not_queued | queued | processing | ready | error
                "items": None,
                "error": None,
                "updated_at_ms": _now_ms(),
            }
            ANALYSIS_STORE[transcript_id] = rec
        return dict(rec)


def enqueue_analysis(transcript_id: str, fireflies_api_key: str, gemini_api_key: str = None, force: bool = False) -> Tuple[bool, Dict[str, Any]]:
    """
    Enqueues an analysis job if not already ready/processing/queued.
    If force=True, re-enqueues even if 'ready'.
    Returns (True, record).
    """
    if not transcript_id:
        return False, {"error": "transcript_id is required"}
    if not fireflies_api_key:
        return False, {"error": "fireflies_api_key is required"}

    with _lock:
        rec = ANALYSIS_STORE.get(transcript_id)
        if rec:
            status = rec.get("status")
            if status in {"queued", "processing"} or (status == "ready" and not force):
                return True, dict(rec)

        ANALYSIS_STORE[transcript_id] = {
            "transcript_id": transcript_id,
            "status": "queued",
            "items": None,
            "error": None,
            "updated_at_ms": _now_ms(),
        }

    _queue.put(AnalysisJob(transcript_id=transcript_id, fireflies_api_key=fireflies_api_key, gemini_api_key=gemini_api_key or ""))
    return True, get_analysis_record(transcript_id)


def enqueue_analysis_from_text(
    session_id: str,
    transcript_text: str,
    action_items: List[str],
    gemini_api_key: str,
    participants: Optional[List[Dict]] = None,
    force: bool = False,
) -> Tuple[bool, Dict[str, Any]]:
    """
    Enqueues a Gemini analysis job using a pre-built transcript (no Fireflies required).
    Used exclusively by in-person recording sessions.

    The session_id becomes the transcript_id in ANALYSIS_STORE, so the
    existing GET /api/gemini/status/<id> polling endpoint works unchanged.
    """
    if not session_id:
        return False, {"error": "session_id is required"}
    if not gemini_api_key:
        return False, {"error": "gemini_api_key is required"}

    with _lock:
        rec = ANALYSIS_STORE.get(session_id)
        if rec:
            status = rec.get("status")
            if status in {"queued", "processing"} or (status == "ready" and not force):
                return True, dict(rec)

        ANALYSIS_STORE[session_id] = {
            "transcript_id": session_id,
            "status": "queued",
            "items": None,
            "error": None,
            "updated_at_ms": _now_ms(),
        }

    _queue.put(InPersonJob(
        transcript_id=session_id,
        transcript_text=transcript_text,
        action_items=list(action_items),
        gemini_api_key=gemini_api_key,
        participants=list(participants) if participants else [],
    ))
    return True, get_analysis_record(session_id)


def _set_record(transcript_id: str, **updates: Any) -> None:
    with _lock:
        rec = ANALYSIS_STORE.get(transcript_id) or {"transcript_id": transcript_id}
        rec.update(updates)
        rec["updated_at_ms"] = _now_ms()
        ANALYSIS_STORE[transcript_id] = rec


def update_analysis_record(transcript_id: str, items: list) -> bool:
    """
    Updates the items list for an existing analysis record.
    Returns True if updated, False if record doesn't exist.
    """
    with _lock:
        if transcript_id not in ANALYSIS_STORE:
            return False
        ANALYSIS_STORE[transcript_id]["items"] = items
        ANALYSIS_STORE[transcript_id]["updated_at_ms"] = _now_ms()
        return True


def _worker_loop() -> None:
    while True:
        try:
            job = _queue.get(timeout=1)
        except Empty:
            continue

        transcript_id = job.transcript_id

        try:
            _set_record(transcript_id, status="processing", error=None)

            doc_context = ''

            if isinstance(job, InPersonJob):
                # In-person path: transcript text already built by DeepgramSession adapter.
                # Participants list is passed directly — no document context injection.
                transcript_text = job.transcript_text
                action_items = job.action_items
                participants = job.participants  # [{speaker_id, name, email}]
            else:
                # Online path: fetch transcript from Fireflies
                ok, ff_result = get_transcript_full(job.fireflies_api_key, transcript_id)
                if not ok:
                    _set_record(transcript_id, status="error", error=f"Fireflies fetch failed: {ff_result}", items=None)
                    _queue.task_done()
                    continue

                transcript_text = ff_result.get("transcript_text", "")
                action_items = ff_result.get("action_items", [])
                participants = None  # online mode uses aliases from gemini_service

                # Inject document context if any documents are uploaded
                try:
                    from services.document_service import DOCUMENTS, search_documents, format_context_block
                    if DOCUMENTS and job.gemini_api_key:
                        search_query = transcript_text[:500] if transcript_text else ' '.join(action_items[:5])
                        doc_results = search_documents(search_query, job.gemini_api_key)
                        doc_context = format_context_block(doc_results)
                except Exception:
                    pass  # Document context is optional — never block analysis

            # Common path: Gemini enrichment (identical for both modes)
            ok, gemini_result = analyze_action_items(
                transcript_text, action_items,
                api_key=job.gemini_api_key or None,
                participants=participants,
                document_context=doc_context,
            )
            if not ok:
                _set_record(transcript_id, status="error", error=f"Gemini analysis failed: {gemini_result}", items=None)
                _queue.task_done()
                continue

            _set_record(
                transcript_id, status="ready",
                items=gemini_result.get("items", []),
                tldrs=gemini_result,
                grounded_by_docs=bool(doc_context),
                error=None,
            )
            _queue.task_done()
        except Exception as e:
            _set_record(transcript_id, status="error", error=f"Unhandled internal error: {str(e)}", items=None)
            _queue.task_done()


def start_background_worker() -> None:
    """
    Starts the analysis worker exactly once.
    """
    global _worker_started
    if _worker_started:
        return

    with _lock:
        if _worker_started:
            return
        t = threading.Thread(target=_worker_loop, name="gemini-analysis-worker", daemon=True)
        t.start()
        _worker_started = True
